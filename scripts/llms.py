"""Generate llms-full.txt, the full HTTP API reference, from FastAPI's OpenAPI schema.

    uv run python scripts/llms.py           # rewrite llms-full.txt
    uv run python scripts/llms.py --check   # exit 1 if it's out of date (tests/test_llms.py runs this too)

The top of the file is the hand-written llms.txt; everything after it comes
from the routes' signatures, request models and docstrings in server.py.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

OUT = ROOT / "llms-full.txt"
SKIP = {"/api/{rest}", "/{rest}", "/api/{rest:path}", "/{rest:path}"}


def _type(schema: dict, defs: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(_type(s, defs) for s in schema["anyOf"])
    t = schema.get("type", "any")
    if t == "array":
        return f"list[{_type(schema.get('items', {}), defs)}]"
    if t == "object" and "additionalProperties" in schema:
        return "object"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "null"}.get(t, t)


def _fields(model: str, defs: dict, seen: set[str]) -> list[str]:
    schema = defs.get(model, {})
    req = set(schema.get("required", []))
    lines = []
    for name, prop in schema.get("properties", {}).items():
        default = f" = {prop['default']!r}" if "default" in prop else ""
        need = "" if name in req or default else " (optional)"
        lines.append(f"  - `{name}`: {_type(prop, defs)}{default}{need}")
    nested = {
        p["$ref"].rsplit("/", 1)[-1]
        for prop in schema.get("properties", {}).values()
        for p in [prop, prop.get("items", {})] + prop.get("anyOf", [])
        if isinstance(p, dict) and "$ref" in p
    }
    for n in sorted(nested - seen):
        seen.add(n)
        lines.append(f"  - {n}:")
        lines += ["  " + ln for ln in _fields(n, defs, seen)]
    return lines


def generate() -> str:
    from logo_gen.server import app

    spec = app.openapi()
    defs = spec.get("components", {}).get("schemas", {})
    head = (ROOT / "llms.txt").read_text(encoding="utf-8").rstrip() + "\n"
    out = [
        head,
        "",
        "## HTTP API reference",
        "",
        "Generated by `scripts/llms.py` from the server's OpenAPI schema. Everything is JSON under",
        "`http://127.0.0.1:7860/api` unless noted. Errors come back as `{\"error\": \"...\", \"kind\": \"...\"}`",
        "or FastAPI's `{\"detail\": ...}`, with a 4xx or 5xx status.",
        "",
    ]
    for path, ops in spec["paths"].items():
        if path in SKIP:
            continue
        for method, op in ops.items():
            out.append(f"### {method.upper()} {path}")
            out.append("")
            doc = (op.get("description") or "").strip()
            if doc:
                out += [doc, ""]
            params = [p for p in op.get("parameters", []) if p["in"] == "query"]
            if params:
                out.append("Query:")
                for p in params:
                    sch = p.get("schema", {})
                    default = f" = {sch['default']!r}" if "default" in sch else ""
                    out.append(f"  - `{p['name']}`: {_type(sch, defs)}{default}")
                out.append("")
            body = op.get("requestBody", {}).get("content", {})
            if "application/json" in body:
                model = _type(body["application/json"]["schema"], defs)
                out.append(f"Body ({model}):")
                out += _fields(model, defs, {model})
                out.append("")
            elif "multipart/form-data" in body:
                out += ["Body: multipart form data (`images`: one or more image files).", ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    text = generate()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("llms-full.txt is out of date. Run: uv run python scripts/llms.py")
            sys.exit(1)
        print("llms-full.txt is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name} ({len(text):,} bytes)")


if __name__ == "__main__":
    main()
